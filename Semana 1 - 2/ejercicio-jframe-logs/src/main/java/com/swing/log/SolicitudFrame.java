    private void EvaluarButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EvaluarButtonActionPerformed
        
        // FORMAR LOS OBJETOS
        Double ingresoNumero = Double.valueOf(IngresoField.getText());
        Cliente cliente = new Cliente(DniField.getText(), ingresoNumero, NombreField.getText());
        
        Double precioTotal = Double.valueOf(PrecioField.getText());
        Vehiculo vehiculo = new Vehiculo(MarcaCombo.getSelectedItem().toString(), precioTotal);
        
        Double cuotaInicial = Double.valueOf(InicialField.getText());
        SolicitudCredito solicitudCredito = new SolicitudCredito(cliente, cuotaInicial, CuotaCombo.getSelectedItem().toString());
        
        if (!creditoService.sePuedeEndeudar(vehiculo.getPrecio(), cliente.getIngreso())) {
            javax.swing.JOptionPane.showMessageDialog(this, "ERROR: NO TE PUEDES ENDEUDAR", "ERROR!", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        
        if (!creditoService.ingresoApto(cliente.getIngreso())) {
            javax.swing.JOptionPane.showMessageDialog(this, "ERROR: NO PUEDES SOLICITAR CREDITO CON EL INGRESO ACTUAL", "ERROR!", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        
        if (!creditoService.minimoCuotaInicial(solicitudCredito.getCuotaInicial(), cliente.getIngreso())) {
            javax.swing.JOptionPane.showMessageDialog(this, "ERROR: EL MONTO DE CUOTA INICIAL NO ES ADECUADO", "ERROR!", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        
        creditoService.registrarCredito(solicitudCredito, vehiculo);
        javax.swing.JOptionPane.showMessageDialog(this, "INFO: SOLICITUD INGRESADA EXITOSAMENTE", "INFO!", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }//GEN-LAST:event_EvaluarButtonActionPerformed

    private void PrecioFieldKeyTyped(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_PrecioFieldKeyTyped
        char c = evt.getKeyChar();
        
        if(PrecioField.getText().contains(".") && c == '.') {
            evt.consume();
        }
        
        if(!(Character.isDigit(c) || c == '.')) evt.consume();
        
        if(PrecioField.getText().contains(".")) {
            String[] partes = PrecioField.getText().split("\\.");
            
            if (partes.length > 1) {
                String parteDecimal = partes[1];

                // Si ya hay 2 o más decimales, bloqueamos CUALQUIER nueva entrada
                // EXCEPTUANDO las teclas de control como borrar (Backspace es '\b')
                if (parteDecimal.length() >= 2 && evt.getKeyChar() != '\b') {
                    evt.consume();
                }
            }
        }
    }//GEN-LAST:event_PrecioFieldKeyTyped

