    private void editTaskButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_editTaskButtonActionPerformed
        // 1. Obtener la fila seleccionada en la tabla (-1 indica que no hay selección)
        int filaSeleccionada = pendientesTable.getSelectedRow();

            if (filaSeleccionada != -1) {
            // Obtener exactamente la Tarea seleccionada por su índice de fila
            Tarea tareaSeleccionada = listaPendientes.get(filaSeleccionada);

            // Abrir el Dialog pasando la tarea elegida y el repositorio
            TareaDetalleDialog dialog = new TareaDetalleDialog(this, true, tareaSeleccionada, tareaRepository);
            dialog.setVisible(true);

            // Al cerrar el Dialog, refrescar las tablas para actualizar cambios
            cargarTablasTareas();
        } else {
            javax.swing.JOptionPane.showMessageDialog(
                this, 
                "Seleccione una tarea pendiente de la tabla.", 
                "Atención", 
                javax.swing.JOptionPane.WARNING_MESSAGE
            );
        }
    }//GEN-LAST:event_editTaskButtonActionPerformed


