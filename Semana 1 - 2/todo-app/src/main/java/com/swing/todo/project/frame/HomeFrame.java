    private void cargarTablasTareas() {
        DefaultTableModel modelPendientes = (DefaultTableModel) pendientesTable.getModel();
        DefaultTableModel modelCompletadas = (DefaultTableModel) completadosTable.getModel();

        // 1. Limpiar filas de los modelos visuales
        modelPendientes.setRowCount(0);
        modelCompletadas.setRowCount(0);

        // 2. Limpiar listas auxiliares
        listaPendientes.clear();
        listaCompletadas.clear();

        // 3. Obtener todas las tareas del usuario desde el repositorio
        List<Tarea> todasLasTareas = tareaRepository.listarPorPersona(usuarioActual.getId());

        // 4. Clasificar cada tarea
        for (Tarea t : todasLasTareas) {
            Object[] fila = new Object[]{ t.getTarea(), t.getPrioridad() };

            if (t.isCompletada()) {
                listaCompletadas.add(t); // Sincroniza índice con tblCompletadas
                modelCompletadas.addRow(fila);
            } else {
                listaPendientes.add(t);  // Sincroniza índice con tblPendientes
                modelPendientes.addRow(fila);
            }
        }
    }
    
